"""Prepared-dataset release: file manifest (the trust anchor committed to Git), verification and local data YAML.

The release contains the already-cleaned, already-annotated ``yolo-rock-v1.1`` **Config A** training split plus the
validation and test splits, their YOLO labels and the manifests needed to train and evaluate. It does NOT contain the
original source datasets, Config B or anything that requires re-running the preprocessing pipeline.

Integrity model: ``data/release/yolo-rock-v1.1-configA.files.sha256`` lists every file with its SHA-256. It lives in Git,
so a downloaded archive is trusted only if every file matches it (an archive-level SHA-256 is checked as well when the
release record provides one).
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from ..config import paths

RELEASE_NAME = "yolo-rock-v1.1-configA"
RELEASE_DIR = paths.ROOT / "data" / "release"
FILE_MANIFEST = RELEASE_DIR / f"{RELEASE_NAME}.files.sha256"
RELEASE_RECORD = RELEASE_DIR / "dataset_release.json"
LOCAL_YAML = paths.ROOT / "data" / "local" / "data_A.local.yaml"     # git-ignored, machine-specific

INCLUDE = [("config_A/images/train", "*.png"), ("config_A/labels/train", "*.txt"), ("images/val", "*.png"), ("labels/val", "*.txt"),
           ("images/test", "*.png"), ("labels/test", "*.txt")]
INCLUDE_FILES = ["manifests/split_manifest.csv", "manifests/eval_ignore_regions.json",
                 "manifests/eval_ignore_regions_subthreshold_PROPOSED.json", "manifests/dataset_status.json"]
EXPECTED_COUNTS = {"config_A/images/train": 1903, "config_A/labels/train": 1903, "images/val": 923, "labels/val": 923,
                   "images/test": 917, "labels/test": 917}


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def release_files(dataset_root: Path) -> list[str]:
    rels = []
    for sub, pat in INCLUDE:
        rels += sorted(f"{sub}/{p.name}" for p in (dataset_root / sub).glob(pat))
    rels += [f for f in INCLUDE_FILES if (dataset_root / f).exists()]
    return rels


def build_file_manifest(dataset_root: Path) -> list[tuple[str, str, int]]:
    return [(rel, sha256_file(dataset_root / rel), (dataset_root / rel).stat().st_size) for rel in release_files(dataset_root)]


def read_file_manifest(path: Path = FILE_MANIFEST) -> dict[str, str]:
    out = {}
    for ln in path.read_text(encoding="utf-8").splitlines():
        if ln.strip() and not ln.startswith("#"):
            digest, rel = ln.split(maxsplit=1)
            out[rel.strip()] = digest
    return out


def verify_dataset(dataset_root: Path, manifest: dict[str, str] | None = None, full: bool = True, sample_every: int = 50) -> dict:
    """Check presence and SHA-256 of release files. ``full=False`` hashes all labels/manifests and every N-th image."""
    manifest = manifest if manifest is not None else read_file_manifest()
    missing, bad, checked = [], [], 0
    for i, (rel, digest) in enumerate(sorted(manifest.items())):
        p = dataset_root / rel
        if not p.exists():
            missing.append(rel); continue
        if full or not rel.endswith(".png") or i % sample_every == 0:
            checked += 1
            if sha256_file(p) != digest:
                bad.append(rel)
    counts = {sub: sum(1 for r in manifest if r.startswith(sub + "/")) for sub in EXPECTED_COUNTS}
    return {"dataset_root": paths.rel(dataset_root), "files_in_manifest": len(manifest), "hashed": checked, "mode": "full" if full else "quick",
            "missing": missing[:20], "n_missing": len(missing), "mismatched": bad[:20], "n_mismatched": len(bad),
            "counts_match_expected": counts == EXPECTED_COUNTS if all(s in EXPECTED_COUNTS for s in counts) else False,
            "ok": not missing and not bad}


def write_local_data_yaml(dataset_root: Path, out: Path = LOCAL_YAML) -> Path:
    """Ultralytics data YAML pointing at a verified local copy (written outside the dataset folder)."""
    import yaml
    out.parent.mkdir(parents=True, exist_ok=True)
    cfg = {"path": dataset_root.resolve().as_posix(), "train": "config_A/images/train", "val": "images/val", "test": "images/test",
           "names": {0: "rock"}, "nc": 1}
    out.write_text("# Generated by artemis_x.datasets.release - machine-specific, not committed.\n"
                   "# PROVISIONAL labels: automated S2-H VALID boxes, NOT human-verified.\n" + yaml.safe_dump(cfg, sort_keys=False),
                   encoding="utf-8", newline="\n")
    return out


def release_record() -> dict:
    return json.loads(RELEASE_RECORD.read_text(encoding="utf-8"))
